#!/usr/bin/env python3
"""One-off, 2026-11-16: one key field, provenance on records, and the hash fixed.

Three things were wrong with the store, and this puts the files right once:

  1. The content hash covered each label's `fetched_at`, so the 2026-11-15 re-fetch
     of AIID appended a second version of every incident that carries a label - 313
     of them - with nothing of substance changed. The hash now covers substance only
     (run.py record_hash). Every record row's hash is recomputed, and a row whose new
     hash equals the one of the version before it is dropped: it was never a change.
  2. Rows carried their identity only as two fields. Every row in records/, context/,
     proposals/, state/queue.jsonl and state/readiness.jsonl now also carries
     `record_key`, "<source_id>:<source_record_id>".
  3. A record did not say which raw row it came from. Each record row gains `raw_ref`:
     the raw file, the source's own id field and value, and the fetch date. For AIID
     the id is the incident's `_id`, looked up in 0.2/raw/aiid/incidents.jsonl.

context/ and proposals/ are append-only. Here they gain `record_key` and nothing
else: the script checks that every row, read back, equals the row before less that
field, and that the row count is unchanged. A file whose rows were written with sorted
keys (run.py's own format) is rewritten in that format, so the next append does not
move the field again; any other file gets the field put at the front of each line,
the rest of the line untouched.

The queue and readiness are not edited: they are regenerated by the normal stages,
prefilter and readiness, and compared with what was there.

Idempotent: a second run finds nothing to do and writes nothing. Run from anywhere:

    python 0.2/pipeline/migrate_keys_20261116.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run as pipeline  # noqa: E402  the pipeline owns the key, the hash and the formats

# What the 2026-11-15 re-fetch did, measured before this script was written.
AIID_SPURIOUS = 313
AIID_INCIDENTS = 1817


def sorted_line(row):
    return json.dumps(row, ensure_ascii=False, sort_keys=True)


def aiid_mongo_ids():
    """incident_id -> _id, from the raw snapshot."""
    path = pipeline.RAW / "aiid" / "incidents.jsonl"
    return {str(r.get("incident_id")): r.get("_id") for r in pipeline.read_jsonl(path)}


def raw_ref_for(row, mongo):
    """Where a record that predates raw_ref came from. Only what is known is written."""
    sid, rid = row["source_id"], str(row["source_record_id"])
    meta = row.get("meta") or {}
    fetched = row.get("fetched_at") or ""
    if sid == "aiid":
        if rid not in mongo:
            sys.exit(f"aiid:{rid} is not in 0.2/raw/aiid/incidents.jsonl; cannot find its _id")
        return {"path": "0.2/raw/aiid/incidents.jsonl", "id_field": "_id",
                "id": mongo[rid], "fetched_at": fetched}
    if meta.get("poc_event_id"):
        # carried over by migrate_poc.py from the frozen PoC inventory
        return {"path": "poc/data/incidents.csv", "id_field": "event_id",
                "id": meta["poc_event_id"], "fetched_at": fetched}
    if sid == pipeline.MANUAL and meta.get("raw_file"):
        return {"path": f"0.2/raw/manual/{meta['raw_file']}", "id_field": "source_record_id",
                "id": rid, "fetched_at": fetched}
    return {"path": f"0.2/raw/{sid}/", "id_field": "source_record_id", "id": rid,
            "fetched_at": fetched}


def migrate_records(mongo):
    """Recompute hashes, drop identical versions, add record_key and raw_ref."""
    report = {}
    for path in sorted(pipeline.RECORDS.glob("*.jsonl")):
        rows = pipeline.read_jsonl(path)
        last, out, dropped, keyed, reffed, rehashed = {}, [], 0, 0, 0, 0
        for row in rows:
            pair = (row["source_id"], str(row["source_record_id"]))
            new_hash = pipeline.record_hash(row)
            if last.get(pair) == new_hash:
                dropped += 1
                continue
            last[pair] = new_hash
            row = dict(row)
            if row.get("content_hash") != new_hash:
                row["content_hash"] = new_hash
                rehashed += 1
            if row.get("record_key") != pipeline.record_key(*pair):
                row["record_key"] = pipeline.record_key(*pair)
                keyed += 1
            if "raw_ref" not in row:
                row["raw_ref"] = raw_ref_for(row, mongo)
                reffed += 1
            out.append(row)
        if dropped or keyed or reffed or rehashed:
            pipeline.write_jsonl(path, out)
        report[path.name] = {"rows_before": len(rows), "rows_after": len(out),
                             "dropped": dropped, "rehashed": rehashed,
                             "record_key_added": keyed, "raw_ref_added": reffed,
                             "records": len(last)}
    return report


def add_key_only(path):
    """Add record_key to an append-only file and change nothing else. Verified."""
    lines = path.read_text(encoding="utf-8").splitlines()
    before = [json.loads(l) for l in lines if l.strip()]
    if all("record_key" in r for r in before):
        return {"rows": len(before), "record_key_added": 0}
    was_sorted = all(sorted_line(r) == l.strip() for r, l in
                     zip(before, [l for l in lines if l.strip()]))
    out_lines, added = [], 0
    for line in lines:
        if not line.strip():
            out_lines.append(line)
            continue
        row = json.loads(line)
        if "record_key" in row:
            out_lines.append(line)
            continue
        key = pipeline.record_key(row["source_id"], row["source_record_id"])
        added += 1
        if was_sorted:
            out_lines.append(sorted_line({**row, "record_key": key}))
        else:
            stripped = line.lstrip()
            assert stripped.startswith("{"), f"{path}: a line is not a JSON object"
            body = stripped[1:].lstrip()
            sep = "" if body.startswith("}") else ", "
            out_lines.append(line[:len(line) - len(stripped)] + "{"
                             + json.dumps({"record_key": key}, ensure_ascii=False)[1:-1]
                             + sep + body)
    after = [json.loads(l) for l in out_lines if l.strip()]
    # the verification: same rows, same content, only the field added
    if len(after) != len(before):
        sys.exit(f"{path}: row count changed {len(before)} -> {len(after)}; nothing written")
    for n, (a, b) in enumerate(zip(before, after), 1):
        if {k: v for k, v in b.items() if k != "record_key"} != a or \
                b["record_key"] != pipeline.record_key(b["source_id"], b["source_record_id"]):
            sys.exit(f"{path}:{n}: the row would change beyond record_key; nothing written")
    path.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    return {"rows": len(after), "record_key_added": added,
            "format": "sorted keys" if was_sorted else "field put first, line kept"}


def strip_key(rows):
    return [{k: v for k, v in r.items() if k != "record_key"} for r in rows]


def main():
    mongo = aiid_mongo_ids()

    print("records/")
    rec = migrate_records(mongo)
    for name, r in rec.items():
        print(f"  {name}: {r}")
    aiid = rec.get("aiid.jsonl")
    if aiid:
        if aiid["dropped"] not in (0, AIID_SPURIOUS):
            sys.exit(f"aiid: dropped {aiid['dropped']} versions, expected {AIID_SPURIOUS} "
                     f"(or 0 on a re-run)")
        if aiid["records"] != AIID_INCIDENTS or aiid["rows_after"] != AIID_INCIDENTS:
            sys.exit(f"aiid: {aiid['rows_after']} rows for {aiid['records']} records, "
                     f"expected {AIID_INCIDENTS} of each")

    for folder in (pipeline.CONTEXT, pipeline.PROPOSALS):
        print(f"{folder.relative_to(pipeline.ROOT)}/")
        for path in sorted(folder.glob("*.jsonl")):
            print(f"  {path.name}: {add_key_only(path)}")

    print("state/: regenerated by prefilter and readiness")
    old_queue = strip_key(pipeline.read_jsonl(pipeline.STATE / "queue.jsonl"))
    old_ready = strip_key(pipeline.read_jsonl(pipeline.STATE / "readiness.jsonl"))
    pipeline.stage_prefilter()
    pipeline.stage_readiness()
    new_queue = pipeline.read_jsonl(pipeline.STATE / "queue.jsonl")
    new_ready = pipeline.read_jsonl(pipeline.STATE / "readiness.jsonl")
    same_q = strip_key(new_queue) == old_queue
    same_r = strip_key(new_ready) == old_ready
    print(f"  queue.jsonl: {len(old_queue)} -> {len(new_queue)} rows, "
          f"{'identical apart from record_key' if same_q else 'CHANGED'}")
    print(f"  readiness.jsonl: {len(old_ready)} -> {len(new_ready)} rows, "
          f"{'identical apart from record_key' if same_r else 'CHANGED'}")
    if not (same_q and same_r):
        sys.exit("the regenerated queue or readiness differs from before the migration")


if __name__ == "__main__":
    main()
